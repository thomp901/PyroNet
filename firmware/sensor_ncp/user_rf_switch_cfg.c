#include "ti_drivers_config.h"
#include <ti/drivers/GPIO.h>
#include <ti/drivers/rf/RF.h>

/*
 *  ======== rfDriverCallbackAntennaSwitching ========
 *  Configure the BDE module RF switch for the active RF path.
 *
 *  Notes:
 *  - CONFIG_RF_ANTENNA_PIN_SUB_1_G and CONFIG_RF_ANTENNA_PIN_HIGH_PA are
 *    generated by SysConfig once the RF driver is configured.
 *  - For the BDE module, these two logical antenna pins should be mapped onto
 *    the module's internal RF switch control pins DIO29 and DIO30.
 */
void rfDriverCallbackAntennaSwitching(RF_Handle client,
                                      RF_GlobalEvent events,
                                      void *arg)
{
    if (events & RF_GlobalEventRadioSetup) {
        bool sub1GHz = false;
        uint8_t loDivider = 0;

        /* Put both RF switch control pins in the "off" state first. */
        GPIO_write(CONFIG_RF_ANTENNA_PIN_SUB_1_G, 0);
        GPIO_write(CONFIG_RF_ANTENNA_PIN_HIGH_PA, 0);

        /* Determine whether the current setup is using the Sub-1 GHz front end. */
        RF_TxPowerTable_PAType paType =
            (RF_TxPowerTable_PAType)RF_getTxPower(client).paType;
        RF_RadioSetup *setupCommand = (RF_RadioSetup *)arg;

        switch (setupCommand->common.commandNo) {
            case CMD_RADIO_SETUP:
            case CMD_BLE5_RADIO_SETUP:
                loDivider = RF_LODIVIDER_MASK & setupCommand->common.loDivider;
                if (loDivider != 0) {
                    sub1GHz = true;
                }
                break;

            case CMD_PROP_RADIO_DIV_SETUP:
                loDivider = RF_LODIVIDER_MASK & setupCommand->prop_div.loDivider;
                if (loDivider != 0) {
                    sub1GHz = true;
                }
                break;

            default:
                break;
        }

        if (sub1GHz) {
            if (paType == RF_TxPowerTable_HighPA) {
                /*
                 * High-power TX path:
                 *   DIO29 = 1
                 *   DIO30 = 0
                 *
                 * RFC_GPO3 is used as the PA-enable work-around used in TI
                 * examples for CC1352P-class devices.
                 */
                GPIO_setConfigAndMux(CONFIG_RF_ANTENNA_PIN_SUB_1_G,
                                     GPIO_CFG_OUTPUT,
                                     IOC_PORT_RFC_GPO0);
                GPIO_setConfigAndMux(CONFIG_RF_ANTENNA_PIN_HIGH_PA,
                                     GPIO_CFG_OUTPUT,
                                     IOC_PORT_RFC_GPO3);
            }
            else {
                /*
                 * Sub-1 GHz receive / non-HighPA path:
                 *   DIO29 = 0
                 *   DIO30 = 1
                 */
                GPIO_setConfigAndMux(CONFIG_RF_ANTENNA_PIN_HIGH_PA,
                                     GPIO_CFG_OUTPUT,
                                     IOC_PORT_GPIO);
                GPIO_setConfigAndMux(CONFIG_RF_ANTENNA_PIN_SUB_1_G,
                                     GPIO_CFG_OUTPUT | GPIO_CFG_OUT_HIGH,
                                     IOC_PORT_GPIO);
            }
        }
    }
    else if (events & RF_GlobalEventRadioPowerDown) {
        /* Restore both RF switch control pins to the "off" state. */
        GPIO_write(CONFIG_RF_ANTENNA_PIN_SUB_1_G, 0);
        GPIO_write(CONFIG_RF_ANTENNA_PIN_HIGH_PA, 0);

        /* Return the mux settings to plain GPIO when the radio powers down. */
        GPIO_setConfigAndMux(CONFIG_RF_ANTENNA_PIN_SUB_1_G,
                             GPIO_CFG_OUTPUT,
                             IOC_PORT_GPIO);
        GPIO_setConfigAndMux(CONFIG_RF_ANTENNA_PIN_HIGH_PA,
                             GPIO_CFG_OUTPUT,
                             IOC_PORT_GPIO);
    }
}

