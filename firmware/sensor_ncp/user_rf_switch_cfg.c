/*
 *  ======== user_rf_switch_cfg.c ========
 *
 *  Commented stub for the BDE-MB1352P71 RF switch configuration.
 *
 *  Why this file exists:
 *  - The BDE module uses a different Sub-1 GHz RF switch truth table than the
 *    TI LP_CC1352P7_1 LaunchPad examples.
 *  - The BDE module routes DIO29/DIO30 internally to the RF switch.
 *  - RF switch behavior must be controlled by the RF driver callback, not by
 *    ordinary application GPIO toggling.
 *
 *  BDE truth table:
 *      Off : DIO29 = 0, DIO30 = 0
 *      TX  : DIO29 = 1, DIO30 = 0
 *      RX  : DIO29 = 0, DIO30 = 1
 *
 *  Important:
 *  - This project template does not currently instantiate the RF driver, so
 *    this file is intentionally a stub and is not compiled by the makefiles.
 *  - Before enabling this file, add and configure the RF driver in SysConfig.
 *  - SysConfig must generate the RF antenna pin macros used below, typically:
 *      CONFIG_RF_ANTENNA_PIN_SUB_1_G
 *      CONFIG_RF_ANTENNA_PIN_HIGH_PA
 *  - Those RF pins should map to the BDE module's internal switch control
 *    lines on DIO29 and DIO30.
 *
 *  Integration steps when RF is added later:
 *  1. Add /ti/drivers/RF to the .syscfg.
 *  2. Configure the RF antenna multiplexer pins for the BDE module.
 *  3. Add this file to the active build.
 *  4. Register this callback wherever the chosen stack/example expects the RF
 *     antenna-switch callback to be supplied.
 *
 *  The implementation below is wrapped in #if 0 so the file can live in the
 *  repo as documentation without breaking builds before RF support is enabled.
 */

